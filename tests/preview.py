from pathlib import Path
import ctypes as c
import json
from PIL import Image,ImageOps,ImageDraw
base=Path(__file__).resolve().parent
class Game(c.Structure):
 _fields_=[('x',c.c_int32),('y',c.c_int32),('vx',c.c_int32),('vy',c.c_int32),('deaths',c.c_uint16),('frame',c.c_uint16),('level',c.c_uint8),('stars',c.c_uint8),('grounded',c.c_uint8),('previous_keys',c.c_uint8),('mode',c.c_int)]
lib=c.CDLL(str(base/'render.dylib'))
lib.game_init.argtypes=[c.POINTER(Game)];lib.game_tick.argtypes=[c.POINTER(Game),c.c_uint8];lib.game_render.argtypes=[c.POINTER(Game)]
pixels=(c.c_ubyte*(128*64)).in_dll(lib,'pixels')
def image_from_display():
 return Image.frombytes('L',(128,64),bytes(pixels)).convert('RGB').resize((768,384),Image.Resampling.NEAREST)

out=base.parent/'preview';out.mkdir(exist_ok=True)
title=Game();lib.game_init(c.byref(title));lib.game_render(c.byref(title));image_from_display().save(out/'title.png')
frames=[];shots=[];victory=None
for level,route in enumerate(json.loads((base/'routes.json').read_text())):
 g=Game();lib.game_init(c.byref(g));g.level=level;g.mode=1
 for _ in range(10):lib.game_tick(c.byref(g),0)
 for index,action in enumerate(route):
  for _ in range(4):
   lib.game_tick(c.byref(g),action);lib.game_render(c.byref(g))
   img=image_from_display()
   frames.append(img)
  if index==20:shots.append(img.copy())
 if level==2:
  for _ in range(12):lib.game_tick(c.byref(g),0)
  lib.game_render(c.byref(g));victory=image_from_display()
 frames.extend([frames[-1]]*40)
frames[0].save(out/'gameplay.gif',save_all=True,append_images=frames[1:],duration=20,loop=0)
for i,img in enumerate(shots):img.save(out/f'level-{i+1}.png')
if victory is not None:victory.save(out/'victory.png')
print('Saved previews generated by the firmware C renderer, with host OLED stub.')
